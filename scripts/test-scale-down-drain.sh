#!/usr/bin/env bash
# test-scale-down-drain.sh — Verify graceful shutdown and load absorption on scale-down.
#
# Starts 3 Bolt instances sharing a single Valkey backend, runs concurrent
# queries across all 3, sends SIGTERM to one instance, and verifies:
#   1. In-flight queries on the terminated instance complete (no connection resets)
#   2. Surviving instances continue serving without errors
#   3. Surviving instances absorb the full load
#
# Usage:
#   export VALKEY_PASSWORD='change-me-for-local-dev'
#   ./scripts/test-scale-down-drain.sh
#
# Requirements:
#   - Docker with compose v2 plugin
#   - python3 with neo4j driver (pip install neo4j)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
COMPOSE_FILE="$PROJECT_DIR/docker-compose.drain-test.yml"

# ── Colors ──────────────────────────────────────────────────────────────
if [ -t 1 ]; then
    RED='\033[0;31m'
    GREEN='\033[0;32m'
    YELLOW='\033[1;33m'
    NC='\033[0m'
else
    RED='' GREEN='' YELLOW='' NC=''
fi

log_info()  { echo -e "${YELLOW}[INFO]${NC}  $*"; }
log_pass()  { echo -e "${GREEN}[PASS]${NC}  $*"; }
log_fail()  { echo -e "${RED}[FAIL]${NC}  $*"; }

# ── Validate environment ───────────────────────────────────────────────
if [ -z "${VALKEY_PASSWORD:-}" ]; then
    echo "ERROR: VALKEY_PASSWORD must be set."
    echo "Example: export VALKEY_PASSWORD='change-me-for-local-dev'"
    exit 1
fi
export VALKEY_PASSWORD
export BOLT_PASSWORD="${BOLT_PASSWORD:-$VALKEY_PASSWORD}"

if ! docker compose version &>/dev/null; then
    echo "ERROR: docker compose v2 is required but not found."
    exit 1
fi

if ! python3 -c "import neo4j" 2>/dev/null; then
    echo "ERROR: Python neo4j driver is required. Install with: pip install neo4j"
    exit 1
fi

# ── Generate the 3-instance compose file ───────────────────────────────
# We generate a dedicated compose file with 3 Bolt instances rather than
# relying on an existing one, keeping the test self-contained.
generate_compose_file() {
    cat > "$COMPOSE_FILE" <<'YAMLEOF'
# docker-compose.drain-test.yml — 3 Bolt instances + 1 Valkey for drain testing
# AUTO-GENERATED by test-scale-down-drain.sh

services:
  valkey:
    image: valkey/valkey:8-bookworm
    environment:
      VALKEY_PASSWORD: ${VALKEY_PASSWORD}
    volumes:
      - valkey-data:/data
    command: |
      sh -ec '
        test -n "$$VALKEY_PASSWORD" || { echo "VALKEY_PASSWORD is required" >&2; exit 1; }
        printf "%s\n" \
          "requirepass $$VALKEY_PASSWORD" \
          "save 60 1" \
          "loglevel notice" \
          "maxmemory 256mb" \
          "maxmemory-policy noeviction" \
          >/tmp/valkey.conf
        exec valkey-server /tmp/valkey.conf
      '
    healthcheck:
      test: ["CMD-SHELL", "test -n \"$$VALKEY_PASSWORD\" && REDISCLI_AUTH=\"$$VALKEY_PASSWORD\" valkey-cli ping"]
      interval: 5s
      timeout: 3s
      retries: 10
      start_period: 5s

  bolt-1:
    build:
      context: .
      dockerfile: Dockerfile.bolt
    entrypoint:
      - /bin/sh
      - -ec
      - |
        export BOLT_PASSWORD="${BOLT_PASSWORD:-$VALKEY_PASSWORD}"
        test -n "$BOLT_PASSWORD" || { echo "BOLT_PASSWORD or VALKEY_PASSWORD is required" >&2; exit 1; }
        exec sedandelivery-bolt
    ports:
      - "7687:7687"
      - "7688:7688"
    environment:
      - RUST_LOG=info
      - VALKEY_PASSWORD=${VALKEY_PASSWORD}
      - GQL_REDIS_URL=redis://:${VALKEY_PASSWORD}@valkey:6379
      - BOLT_PASSWORD=${BOLT_PASSWORD}
      - BOLT_IDLE_TIMEOUT_SECS=300
      - BOLT_MAX_CONNECTIONS=1024
    depends_on:
      valkey:
        condition: service_healthy
    healthcheck:
      test: ["CMD", "curl", "-sf", "http://localhost:7688/health"]
      interval: 5s
      timeout: 3s
      retries: 10
      start_period: 15s
    stop_grace_period: 30s

  bolt-2:
    build:
      context: .
      dockerfile: Dockerfile.bolt
    entrypoint:
      - /bin/sh
      - -ec
      - |
        export BOLT_PASSWORD="${BOLT_PASSWORD:-$VALKEY_PASSWORD}"
        test -n "$BOLT_PASSWORD" || { echo "BOLT_PASSWORD or VALKEY_PASSWORD is required" >&2; exit 1; }
        exec sedandelivery-bolt
    ports:
      - "7689:7687"
      - "7690:7688"
    environment:
      - RUST_LOG=info
      - VALKEY_PASSWORD=${VALKEY_PASSWORD}
      - GQL_REDIS_URL=redis://:${VALKEY_PASSWORD}@valkey:6379
      - BOLT_PASSWORD=${BOLT_PASSWORD}
      - BOLT_IDLE_TIMEOUT_SECS=300
      - BOLT_MAX_CONNECTIONS=1024
    depends_on:
      valkey:
        condition: service_healthy
    healthcheck:
      test: ["CMD", "curl", "-sf", "http://localhost:7688/health"]
      interval: 5s
      timeout: 3s
      retries: 10
      start_period: 15s
    stop_grace_period: 30s

  bolt-3:
    build:
      context: .
      dockerfile: Dockerfile.bolt
    entrypoint:
      - /bin/sh
      - -ec
      - |
        export BOLT_PASSWORD="${BOLT_PASSWORD:-$VALKEY_PASSWORD}"
        test -n "$BOLT_PASSWORD" || { echo "BOLT_PASSWORD or VALKEY_PASSWORD is required" >&2; exit 1; }
        exec sedandelivery-bolt
    ports:
      - "7691:7687"
      - "7692:7688"
    environment:
      - RUST_LOG=info
      - VALKEY_PASSWORD=${VALKEY_PASSWORD}
      - GQL_REDIS_URL=redis://:${VALKEY_PASSWORD}@valkey:6379
      - BOLT_PASSWORD=${BOLT_PASSWORD}
      - BOLT_IDLE_TIMEOUT_SECS=300
      - BOLT_MAX_CONNECTIONS=1024
    depends_on:
      valkey:
        condition: service_healthy
    healthcheck:
      test: ["CMD", "curl", "-sf", "http://localhost:7688/health"]
      interval: 5s
      timeout: 3s
      retries: 10
      start_period: 15s
    stop_grace_period: 30s

volumes:
  valkey-data:
YAMLEOF
}

# ── Cleanup ─────────────────────────────────────────────────────────────
LOAD_PIDS=()
TEMP_OUTPUT_FILES=()
cleanup() {
    log_info "Cleaning up..."
    for pid in "${LOAD_PIDS[@]}"; do
        if kill -0 "$pid" 2>/dev/null; then
            kill "$pid" 2>/dev/null || true
            wait "$pid" 2>/dev/null || true
        fi
    done
    for f in "${TEMP_OUTPUT_FILES[@]}"; do
        rm -f "$f" 2>/dev/null || true
    done
    VALKEY_PASSWORD="$VALKEY_PASSWORD" BOLT_PASSWORD="$BOLT_PASSWORD" \
        docker compose -f "$COMPOSE_FILE" down -v --remove-orphans --timeout 10 2>/dev/null || true
    rm -f "$COMPOSE_FILE" 2>/dev/null || true
}
trap cleanup EXIT

# ── Load generator for a single Bolt instance ─────────────────────────
# Outputs JSON results line when done.
run_load_for_instance() {
    local uri="$1"
    local instance_name="$2"
    local duration="$3"
    local output_file="$4"

    python3 -u - "$BOLT_PASSWORD" "$uri" "$instance_name" "$duration" > "$output_file" 2>&1 <<'PYEOF'
import sys
import time
import json
from neo4j import GraphDatabase
from neo4j.exceptions import ServiceUnavailable, SessionExpired

password = sys.argv[1]
uri = sys.argv[2]
instance_name = sys.argv[3]
duration = int(sys.argv[4])
graph_name = "__drain_test"

driver = GraphDatabase.driver(uri, auth=("neo4j", password),
                              connection_timeout=5, max_transaction_retry_time=3)

writes = 0
errors = 0
connection_resets = 0
deadline = time.time() + duration

while time.time() < deadline:
    try:
        with driver.session() as s:
            s.run(f"USE {graph_name} CREATE (:DrainNode {{instance: '{instance_name}', seq: {writes}, ts: {time.time()}}})").consume()
        writes += 1
    except (ServiceUnavailable, SessionExpired, ConnectionError, OSError) as e:
        errors += 1
        ename = type(e).__name__
        if "reset" in str(e).lower() or "ConnectionReset" in ename:
            connection_resets += 1
            print(f"  [{instance_name}] CONNECTION RESET: {e}", file=sys.stderr)
        else:
            print(f"  [{instance_name}] Error: {ename}: {e}", file=sys.stderr)
    except Exception as e:
        errors += 1
        print(f"  [{instance_name}] Unexpected: {type(e).__name__}: {e}", file=sys.stderr)
    time.sleep(0.05)

result = {
    "instance": instance_name,
    "writes": writes,
    "errors": errors,
    "connection_resets": connection_resets
}
print(f"LOAD_RESULT:{json.dumps(result)}")
driver.close()
PYEOF
}

# ── Wait for service health ────────────────────────────────────────────
wait_for_health() {
    local url="$1"
    local name="$2"
    local max_wait="${3:-90}"
    for i in $(seq 1 "$max_wait"); do
        if curl -sf "$url" &>/dev/null; then
            log_info "$name is healthy (after ${i}s)"
            return 0
        fi
        if [ "$i" -eq "$max_wait" ]; then
            log_fail "$name did not become healthy within ${max_wait}s"
            return 1
        fi
        sleep 1
    done
}

# ── Main ───────────────────────────────────────────────────────────────
main() {
    local passed=0
    local failed=0

    echo "================================================================"
    echo "  Scale-Down Drain Test"
    echo "================================================================"

    cd "$PROJECT_DIR"

    # Generate and start the 3-instance compose stack
    log_info "Generating 3-instance compose file..."
    generate_compose_file

    # Ensure clean state
    cleanup 2>/dev/null || true
    # Regenerate after cleanup removed it
    generate_compose_file

    log_info "Building and starting 3 Bolt instances..."
    VALKEY_PASSWORD="$VALKEY_PASSWORD" BOLT_PASSWORD="$BOLT_PASSWORD" \
        docker compose -f "$COMPOSE_FILE" up -d --build

    # Wait for all three instances
    wait_for_health "http://localhost:7688/health" "bolt-1" 120 || exit 1
    wait_for_health "http://localhost:7690/health" "bolt-2" 120 || exit 1
    wait_for_health "http://localhost:7692/health" "bolt-3" 120 || exit 1

    # Create the test graph via bolt-1
    log_info "Creating test graph..."
    python3 -c "
from neo4j import GraphDatabase
d = GraphDatabase.driver('bolt://localhost:7687', auth=('neo4j', '$BOLT_PASSWORD'))
with d.session() as s:
    try:
        s.run('DROP GRAPH __drain_test').consume()
    except: pass
    s.run('CREATE GRAPH __drain_test').consume()
d.close()
print('  Test graph created')
"

    # ── Phase 1: All 3 instances handle load ────────────────────────────
    echo ""
    log_info "=== Phase 1: Concurrent load on all 3 instances (15s) ==="
    LOAD_DURATION=15

    OUT1=$(mktemp) OUT2=$(mktemp) OUT3=$(mktemp)
    TEMP_OUTPUT_FILES+=("$OUT1" "$OUT2" "$OUT3")

    run_load_for_instance "bolt://localhost:7687" "bolt-1" "$LOAD_DURATION" "$OUT1" &
    LOAD_PIDS+=($!)
    run_load_for_instance "bolt://localhost:7689" "bolt-2" "$LOAD_DURATION" "$OUT2" &
    LOAD_PIDS+=($!)
    run_load_for_instance "bolt://localhost:7691" "bolt-3" "$LOAD_DURATION" "$OUT3" &
    LOAD_PIDS+=($!)

    # Wait for phase 1 to complete
    for pid in "${LOAD_PIDS[@]}"; do
        wait "$pid" 2>/dev/null || true
    done
    LOAD_PIDS=()

    # Parse phase 1 results and verify at least some writes succeeded
    PHASE1_TOTAL_WRITES=0
    for outfile in "$OUT1" "$OUT2" "$OUT3"; do
        RESULT_LINE=$(grep "^LOAD_RESULT:" "$outfile" 2>/dev/null | head -1 | sed 's/^LOAD_RESULT://')
        if [ -n "$RESULT_LINE" ]; then
            INST=$(echo "$RESULT_LINE" | python3 -c "import sys,json; print(json.load(sys.stdin)['instance'])")
            WRITES=$(echo "$RESULT_LINE" | python3 -c "import sys,json; print(json.load(sys.stdin)['writes'])")
            ERRORS=$(echo "$RESULT_LINE" | python3 -c "import sys,json; print(json.load(sys.stdin)['errors'])")
            log_info "  $INST: $WRITES writes, $ERRORS errors"
            PHASE1_TOTAL_WRITES=$((PHASE1_TOTAL_WRITES + WRITES))
        fi
    done
    rm -f "$OUT1" "$OUT2" "$OUT3"

    if [ "$PHASE1_TOTAL_WRITES" -gt 0 ]; then
        log_pass "Phase 1: All 3 instances handled concurrent load ($PHASE1_TOTAL_WRITES total writes)"
        passed=$((passed + 1))
    else
        log_fail "Phase 1: No writes succeeded across any instance"
        failed=$((failed + 1))
    fi

    # ── Phase 2: SIGTERM bolt-3 while running load ──────────────────────
    echo ""
    log_info "=== Phase 2: SIGTERM bolt-3 during active load ==="
    LOAD_DURATION=30

    OUT1=$(mktemp) OUT2=$(mktemp) OUT3=$(mktemp)
    TEMP_OUTPUT_FILES+=("$OUT1" "$OUT2" "$OUT3")

    # Start load on all 3 instances
    run_load_for_instance "bolt://localhost:7687" "bolt-1" "$LOAD_DURATION" "$OUT1" &
    LOAD_PIDS+=($!)
    PID_LOAD1=${LOAD_PIDS[-1]}

    run_load_for_instance "bolt://localhost:7689" "bolt-2" "$LOAD_DURATION" "$OUT2" &
    LOAD_PIDS+=($!)
    PID_LOAD2=${LOAD_PIDS[-1]}

    run_load_for_instance "bolt://localhost:7691" "bolt-3" "$LOAD_DURATION" "$OUT3" &
    LOAD_PIDS+=($!)
    PID_LOAD3=${LOAD_PIDS[-1]}

    # Let load run for a few seconds
    sleep 5

    # Send SIGTERM to bolt-3 container (graceful shutdown)
    log_info "Sending SIGTERM to bolt-3..."
    docker compose -f "$COMPOSE_FILE" stop --timeout 30 bolt-3

    log_info "bolt-3 stopped, waiting for remaining load to complete..."

    # Wait for all load generators to finish
    for pid in $PID_LOAD1 $PID_LOAD2 $PID_LOAD3; do
        wait "$pid" 2>/dev/null || true
    done
    LOAD_PIDS=()

    # ── Analyze results ─────────────────────────────────────────────────
    echo ""
    log_info "=== Results ==="

    TOTAL_RESETS=0
    SURVIVOR_ERRORS=0

    for outfile in "$OUT1" "$OUT2" "$OUT3"; do
        RESULT_LINE=$(grep "^LOAD_RESULT:" "$outfile" 2>/dev/null | head -1 | sed 's/^LOAD_RESULT://')
        if [ -n "$RESULT_LINE" ]; then
            INST=$(echo "$RESULT_LINE" | python3 -c "import sys,json; print(json.load(sys.stdin)['instance'])")
            WRITES=$(echo "$RESULT_LINE" | python3 -c "import sys,json; print(json.load(sys.stdin)['writes'])")
            ERRORS=$(echo "$RESULT_LINE" | python3 -c "import sys,json; print(json.load(sys.stdin)['errors'])")
            RESETS=$(echo "$RESULT_LINE" | python3 -c "import sys,json; print(json.load(sys.stdin)['connection_resets'])")
            log_info "  $INST: $WRITES writes, $ERRORS errors, $RESETS connection resets"
            TOTAL_RESETS=$((TOTAL_RESETS + RESETS))
            # Track errors on surviving instances (bolt-1, bolt-2)
            if [ "$INST" != "bolt-3" ]; then
                SURVIVOR_ERRORS=$((SURVIVOR_ERRORS + ERRORS))
            fi
        fi
    done
    rm -f "$OUT1" "$OUT2" "$OUT3"

    # Check 1: No connection resets
    if [ "$TOTAL_RESETS" -eq 0 ]; then
        log_pass "No connection resets detected across all instances"
        passed=$((passed + 1))
    else
        log_fail "$TOTAL_RESETS connection reset(s) detected"
        failed=$((failed + 1))
    fi

    # Check 2: Surviving instances had zero errors
    if [ "$SURVIVOR_ERRORS" -eq 0 ]; then
        log_pass "Surviving instances (bolt-1, bolt-2) had zero errors"
        passed=$((passed + 1))
    else
        log_fail "Surviving instances had $SURVIVOR_ERRORS error(s)"
        failed=$((failed + 1))
    fi

    # Check 3: Surviving instances still healthy after bolt-3 went down
    if curl -sf "http://localhost:7688/health" &>/dev/null; then
        log_pass "bolt-1 is still healthy after bolt-3 shutdown"
        passed=$((passed + 1))
    else
        log_fail "bolt-1 is not healthy after bolt-3 shutdown"
        failed=$((failed + 1))
    fi

    if curl -sf "http://localhost:7690/health" &>/dev/null; then
        log_pass "bolt-2 is still healthy after bolt-3 shutdown"
        passed=$((passed + 1))
    else
        log_fail "bolt-2 is not healthy after bolt-3 shutdown"
        failed=$((failed + 1))
    fi

    # Check 4: Verify surviving instances can still serve queries
    log_info "Verifying surviving instances can serve queries..."
    python3 -c "
from neo4j import GraphDatabase
for uri, name in [('bolt://localhost:7687', 'bolt-1'), ('bolt://localhost:7689', 'bolt-2')]:
    d = GraphDatabase.driver(uri, auth=('neo4j', '$BOLT_PASSWORD'))
    with d.session() as s:
        result = s.run('USE __drain_test MATCH (n:DrainNode) RETURN count(n) AS cnt')
        cnt = result.single()['cnt']
        print(f'  {name}: {cnt} total nodes visible')
    d.close()
" && {
        log_pass "Surviving instances absorbed load and serve reads correctly"
        passed=$((passed + 1))
    } || {
        log_fail "Surviving instances could not serve queries after scale-down"
        failed=$((failed + 1))
    }

    # Cleanup test graph
    python3 -c "
from neo4j import GraphDatabase
d = GraphDatabase.driver('bolt://localhost:7687', auth=('neo4j', '$BOLT_PASSWORD'))
with d.session() as s:
    try:
        s.run('DROP GRAPH __drain_test').consume()
    except: pass
d.close()
" 2>/dev/null || true

    # ── Summary ─────────────────────────────────────────────────────────
    echo ""
    echo "================================================================"
    echo "  Scale-Down Drain Test Results"
    echo "================================================================"
    echo "  Passed: $passed"
    echo "  Failed: $failed"
    echo "================================================================"

    if [ "$failed" -eq 0 ]; then
        log_pass "All scale-down drain tests passed"
        exit 0
    else
        log_fail "$failed test(s) failed"
        log_info "bolt-1 logs:"
        docker compose -f "$COMPOSE_FILE" logs --tail=30 bolt-1 2>/dev/null || true
        log_info "bolt-2 logs:"
        docker compose -f "$COMPOSE_FILE" logs --tail=30 bolt-2 2>/dev/null || true
        exit 1
    fi
}

main "$@"
